create table if not exists public.funcionario (
  id bigint generated by default as identity primary key,
  nome text,
  email text unique,
  cargo text,
  role text,
  posicao_preferencial text,
  created_at timestamptz default now()
);

create table if not exists public.sala (
  id bigint generated by default as identity primary key,
  nome text not null,
  localizacao text,
  tipo text,
  categoria text,
  descricao text,
  capacidade integer,
  status text,
  disponivel boolean default true,
  motivo_manutencao text,
  planta_url text,
  created_at timestamptz default now()
);

create table if not exists public.mesa (
  id bigint generated by default as identity primary key,
  sala_id bigint references public.sala(id) on delete cascade,
  codigo_mesa text not null,
  created_at timestamptz default now()
);

create table if not exists public.posicao (
  id bigint generated by default as identity primary key,
  sala_id bigint references public.sala(id) on delete cascade,
  codigo_cadeira text not null,
  coordenadas_x numeric,
  coordenadas_y numeric,
  status text,
  disponivel boolean default true,
  motivo_manutencao text,
  created_at timestamptz default now()
);

create table if not exists public.imagem_sala (
  id bigint generated by default as identity primary key,
  sala_id bigint references public.sala(id) on delete cascade,
  nome_ambiente text,
  imagem_url text,
  created_at timestamptz default now()
);

create table if not exists public.equipamento (
  id bigint generated by default as identity primary key,
  sala_id bigint references public.sala(id) on delete cascade,
  posicao_id bigint references public.posicao(id) on delete cascade,
  nome text not null,
  descricao text,
  tipo text,
  status text default 'DISPONIVEL',
  created_at timestamptz default now()
);

create table if not exists public.reserva (
  id bigint generated by default as identity primary key,
  funcionario_id bigint references public.funcionario(id) on delete cascade,
  posicao_id bigint references public.posicao(id) on delete set null,
  data_inicio timestamptz default now(),
  data_fim timestamptz,
  status text default 'ATIVA',
  created_at timestamptz default now()
);

