insert into public.mesa (sala_id, codigo_mesa)
select s.id, 'M01'
from public.sala s
where not exists (
  select 1 from public.mesa m where m.sala_id = s.id
);

insert into public.posicao (sala_id, codigo_cadeira, coordenadas_x, coordenadas_y, disponivel)
select
  s.id,
  'P' || lpad(n::text, 2, '0'),
  n,
  1,
  true
from public.sala s
cross join generate_series(1, 4) as n
where not exists (
  select 1 from public.posicao p where p.sala_id = s.id
);
