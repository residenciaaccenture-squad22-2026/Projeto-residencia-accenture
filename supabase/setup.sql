update public.reserva
set status = 'CANCELADA'
where lower(coalesce(status, '')) = 'cancelada';

update public.reserva
set status = 'ATIVA'
where status is null
   or lower(status) in ('ativa', 'pendente', 'confirmada');

update public.sala
set status = case
    when status is null or status = '' then case when coalesce(disponivel, true) then 'DISPONIVEL' else 'INDISPONIVEL' end
    when upper(status) in ('DISPONIVEL', 'INDISPONIVEL', 'MANUTENCAO') then upper(status)
    else case when coalesce(disponivel, true) then 'DISPONIVEL' else 'INDISPONIVEL' end
  end;

update public.sala
set disponivel = status = 'DISPONIVEL';

update public.posicao
set status = case
    when status is null or status = '' then case when coalesce(disponivel, true) then 'DISPONIVEL' else 'INDISPONIVEL' end
    when upper(status) in ('DISPONIVEL', 'INDISPONIVEL', 'MANUTENCAO') then upper(status)
    else case when coalesce(disponivel, true) then 'DISPONIVEL' else 'INDISPONIVEL' end
  end;

update public.posicao
set disponivel = status = 'DISPONIVEL';

